/*
 * The approved-course lists behind UGA's university-wide and college-wide
 * graduation rules (uga-university-rules.ts), read 2026-10-29 from the pages
 * named above each list (cached copies of 2026-10-28). Each list keeps the
 * course numbers the pages print that UGA's catalog file has
 * (public/uga-catalog.json); a cross-listed course is listed under each of
 * its subjects, a course's graduate number is left out. `ranges` are the
 * pages' subject-wide lines ("All 3-hour, 1000-5999 ANTH courses"), read
 * against the catalog when the rules are applied (3-hour courses only where
 * the page says so).
 */

/** "All 3-hour, 1000-5999 ANTH courses": a subject's course numbers from..to. */
export interface UgaSubjectRange {
  subject: string;
  from: number;
  to: number;
}

export interface UgaRuleList {
  codes: readonly string[];
  ranges?: readonly UgaSubjectRange[];
  /** Codes the page rules out of its own ranges. */
  excluded?: readonly string[];
}

